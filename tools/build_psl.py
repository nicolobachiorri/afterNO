"""Build extension/lib/psl-data.ts from a copy of the Public Suffix List.

The list decides which hosts belong to the same "site" (www.example.co.uk and
shop.example.co.uk do; alice.github.io and bob.github.io do not). Browsers use it for
SameSite and cookie partitioning, so the extension uses the same list.

Usage: python3 tools/build_psl.py path/to/public_suffix_list.dat
Source: https://publicsuffix.org/list/public_suffix_list.dat (Mozilla Public License 2.0).
Both sections are kept, ICANN and private domains, as browsers do.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text(encoding="utf-8")
version = re.search(r"// VERSION: (\S+)", src)
rules = []
for line in src.splitlines():
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    rule = line.split()[0].lower()
    rules.append(rule.encode("idna").decode("ascii") if not rule.isascii() and "*" not in rule and "!" not in rule else rule)
rules = sorted(set(rules))
out = Path(__file__).resolve().parent.parent / "extension" / "lib" / "psl-data.ts"
out.write_text(
    "// Generated by tools/build_psl.py from the Public Suffix List"
    f" (version {version.group(1) if version else 'unknown'}).\n"
    "// Source: https://publicsuffix.org/list/ - Mozilla Public License 2.0. Do not edit by hand.\n"
    f"export const PSL_RULES = {repr(chr(10).join(rules))!s};\n".replace("\\n", "\\n"),
    encoding="utf-8",
)
print(f"{len(rules)} rules -> {out}")
